<?php

namespace App\Modules\Task\Domain\ValueObjects;

/**
 * Колонки канбан-доски.
 *
 * Набор одинаков на всех уровнях: инициативы, проекты и задачи раскладываются
 * по одним и тем же колонкам, меняется только правило перехода между ними.
 * `complete` — «Готово», `canceled` — «Отмена» (американское написание через
 * одну «l»).
 */
enum CardColumn: string
{
    case Backlog = 'backlog';
    case InProgress = 'in_progress';
    case Complete = 'complete';
    case Canceled = 'canceled';

    /**
     * Сколько карточек отдаётся на первичной загрузке доски по каждой паре
     * «уровень + закрытая колонка».
     *
     * Закрытые колонки копят карточки без ограничения (в них уходит всё, что
     * доведено или отменено), поэтому целиком они не грузятся: первичный список
     * содержит последние карточки, а остальные клиент догружает страницами.
     * Лимит считается на пару, а не на колонку и не на уровень: у каждого
     * уровня своя лента «показать ещё», поэтому карточки одного уровня не
     * съедают лимит другого.
     */
    public const int CLOSED_CARDS_PER_LEVEL = 10;

    /**
     * Закрытая ли колонка.
     *
     * У закрытых колонок карточки больше не двигаются по доске, они только
     * накапливаются — поэтому и объём их отдачи на первичной загрузке
     * ограничен (см. CLOSED_CARDS_PER_LEVEL).
     */
    public function isClosed(): bool
    {
        return match ($this) {
            self::Complete, self::Canceled => true,
            self::Backlog, self::InProgress => false,
        };
    }

    /**
     * Подпись колонки для интерфейса и сообщений об ошибках.
     */
    public function label(): string
    {
        return match ($this) {
            self::Backlog => 'Беклог',
            self::InProgress => 'В работе',
            self::Complete => 'Готово',
            self::Canceled => 'Отмена',
        };
    }

    /**
     * Имеет ли смысл степень проработки (флаг «идея») в этой колонке.
     *
     * Степень проработки — свойство беклога: там карточка либо ещё идея, либо
     * уже готова к реализации. В остальных колонках работа идёт по карточке,
     * которая из беклога ушла, поэтому интерфейс выбор не показывает. Само
     * значение флага при переходе не сбрасывается — его видно снова, если
     * карточку вернули в беклог.
     */
    public function acceptsIdeas(): bool
    {
        return $this === self::Backlog;
    }

    /**
     * Все колонки в порядке доски слева направо.
     *
     * @return list<self>
     */
    public static function ordered(): array
    {
        return [self::Backlog, self::InProgress, self::Complete, self::Canceled];
    }
}
