<?php

namespace App\Modules\Task\Application\Results;

/**
 * Результат списка карточек.
 *
 * Кроме самих карточек отдаём признаки выборки: сколько всего карточек
 * подходит под фильтр, сколько их в каждой колонке и сколько закрытых
 * карточек в каждой паре «уровень + колонка». По счётчику пары клиент
 * показывает её число и понимает, остались ли карточки для догрузки:
 * «есть ещё» — это сравнение счётчика с уже загруженным количеством,
 * отдельный признак не нужен.
 *
 * Счётчики считаются по фильтрам, а не по отданной выборке: на первичной
 * загрузке закрытые карточки урезаны, и полный счётчик — единственный способ
 * узнать, что за пределами порции есть ещё карточки.
 */
final readonly class ListTasksResult
{
    /**
     * @param  list<TaskResult>  $items
     * @param  int  $total  всего карточек под фильтром (не только на странице)
     * @param  array<string, int>  $totalByColumn  ключ колонки => всего карточек колонки под фильтром
     * @param  array<string, array<string, int>>  $closedByLevel  ключ колонки => [тип карточки => всего карточек]
     */
    public function __construct(
        public array $items,
        public int $total,
        public array $totalByColumn = [],
        public array $closedByLevel = [],
    ) {}
}
