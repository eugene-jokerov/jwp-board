<?php

namespace App\Shared\Application\Bus;

/**
 * Шина запросов CQRS: точка входа для сценариев чтения.
 *
 * Отдельная от CommandBus, потому что запросы не меняют состояние: у них нет
 * транзакционного пайпа, и они не должны попадать в очередь.
 */
interface QueryBus
{
    /**
     * Выполнить запрос и вернуть результат его хендлера.
     *
     * @param  object  $query  запрос прикладного слоя
     * @return mixed результат хендлера (сущность, коллекция или объект-ответ)
     */
    public function ask(object $query): mixed;
}
