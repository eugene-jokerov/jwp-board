        </p>

        <h2>2. Что такое файлы cookie</h2>
        <p>
          2.1. Cookie — небольшие текстовые файлы, которые сайт сохраняет в браузере. При следующих
          обращениях браузер отправляет их на сервер. Они позволяют сервису «узнавать» сессию
          пользователя и защищать запросы от подделки.
        </p>
        <p>
          2.2. Аналогичные технологии. В мобильном приложении cookie браузера не используются: токен
          доступа хранится в защищённом хранилище устройства (SecureStore) и передаётся серверу в
          заголовке запроса.
        </p>

        <h2>3. Какие cookie мы используем</h2>
        <div class="callout">
          <p>
            <strong>Только технически необходимые cookie.</strong>
            Аналитических, рекламных, трекинговых и сторонних cookie сервис не использует, поэтому
            запрос дополнительного согласия на их установку не требуется: они обеспечивают работу
            функций, которые пользователь запрашивает сам.
          </p>
        </div>

        <h3>3.1. Сессия веб-клиента</h3>
        <p>
          Имя: <code>jwp_board_session</code> (формируется из имени приложения). Назначение:
          хранение идентификатора аутентифицированной сессии, чтобы не передавать логин и пароль при
          каждом запросе. Срок: до 120 минут бездействия или до выхода из учётной записи. Флаги:
          HttpOnly, SameSite=Lax; на HTTPS — Secure.
        </p>

        <h3>3.2. Защита от подделки запросов</h3>
        <p>
          Имя: <code>XSRF-TOKEN</code>. Назначение: CSRF-токен, который клиент возвращает серверу в
          заголовке <code>X-XSRF-TOKEN</code>; сервер проверяет его на каждом изменяющем запросе
          веб-клиента. Срок: в пределах сессии.
        </p>

        <h3>3.3. Токен мобильного клиента</h3>
        <p>
          Cookie не используется: токен доступа хранится в SecureStore операционной системы и
          действует до выхода из учётной записи или отзыва токена сервером.
        </p>

        <h2>4. Что cookie не делают</h2>
        <ul>
          <li>не содержат пароля и не позволяют прочитать его;</li>
          <li>не используются для показа рекламы и профилирования;</li>
          <li>не передаются рекламным сетям, аналитическим платформам и иным третьим лицам;</li>
          <li>не собирают данные о других сайтах, которые посещает пользователь.</li>
        </ul>

        <h2>5. Управление cookie</h2>
        <p>
          5.1. Пользователь может удалить сохранённые cookie и запретить их приём в настройках
          браузера. Поскольку cookie сервиса технически необходимы, при их блокировке вход в
          веб-версию станет невозможен: сервер не сможет связать запросы с сессией. Мобильное
          приложение при этом продолжит работать.
        </p>
        <p>
          5.2. Выход из учётной записи завершает веб-сессию и делает сохранённые cookie сессии
          недействительными.
        </p>
        <p>5.3. Вопросы по использованию cookie направляются на {{ $contactEmail }}.</p>

