            использование, удаление.
          </p>
          <p>
            <strong>Оператор</strong> — лицо, самостоятельно организующее обработку персональных
            данных и определяющее её цели и состав.
          </p>
          <p>
            <strong>Пользователь</strong> — зарегистрировавшийся в сервисе пользователь, то есть
            субъект персональных данных.
          </p>
          <p>
            <strong>Сервис</strong> — веб-версия и мобильное приложение JWP Board для
            персонального планирования.
          </p>
