          </li>
          <li>журналы сервера (IP-адрес, время обращения) — не более 12 месяцев с момента записи;</li>
          <li>
            обращения пользователей — до завершения рассмотрения обращения и срока хранения,
            установленного законодательством.
          </li>
        </ul>
