<?php

/*
|--------------------------------------------------------------------------
| Направления доски
|--------------------------------------------------------------------------
| Ограничение числа направлений на одного пользователя. Палитра направлений
| конечна, а доска должна оставаться обозримой, поэтому лимит — доменное
| правило (Domain\Services\DirectionManager), а число задаётся здесь.
|
| Значение читается только из config('direction.max_per_user'): доменный слой
| получает его через конструктор сервиса (Infrastructure\Providers\
| DirectionServiceProvider), контроллер — для meta.limit в ответе API, чтобы
| клиент показывал счётчик «n из k» и не дублировал число у себя.
|
| Переменная окружения — DIRECTIONS_MAX_PER_USER (см. backend/.env.example).
| env() допустим здесь: обращение идёт из config/*.php.
*/

return [
    /*
    | Максимум направлений на пользователя. Значение обязано быть положительным:
    | при нуле или отрицательном числе направление нельзя было бы создать вовсе,
    | поэтому такие значения заменяются запасным DEFAULT_MAX_PER_USER.
    */
    'max_per_user' => (static function (): int {
        $limit = filter_var(env('DIRECTIONS_MAX_PER_USER', 15), FILTER_VALIDATE_INT);

        return is_int($limit) && $limit > 0 ? $limit : 15;
    })(),
];
