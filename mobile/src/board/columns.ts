/**
 * Раскладка колонок широкого режима доски.
 *
 * Здесь же — тип состояния «колонка свёрнута»: свёрнутая колонка превращается
 * в узкую полосу с вертикальным названием, её карточки не рендерятся.
 * Состояние ведёт каждый уровень доски отдельно, но хранится оно не в компоненте,
 * а в настройках пользователя (`useBoardSettings`): свернув колонку на
 * стратегическом уровне, на тактическом и операционном она остаётся
 * развёрнутой, и этот выбор переживает перезагрузку страницы.
 */

/** Свёрнутые колонки: ключ — id колонки, true — свёрнута. */
export type CollapsedColumns = Record<string, boolean>;

/**
 * Минимальная высота развёрнутой колонки.
 *
 * Колонки лежат в одной flex-строке (`items-start`), поэтому высота самой
 * высокой задаёт высоту узкой полосы свёрнутой колонки — она тянется на всю
 * высоту доски, как в Jira.
 */
export const COLUMN_MIN_HEIGHT = 360;
