/**
 * Карточка доски: белая плитка в рамке, полоса цвета родителя в левом боку,
 * название и иконка действия над колонками.
 *
 * Цвет наследуется по иерархии (направление → инициатива → проект) и живёт только
 * в полосе слева: заливки у карточки нет, рамка отделяет её от колонки.
 *
 * Действие зависит от колонки: в «Беклоге» — «Взять в работу», в «В работе» —
 * «Завершить задачу», в «Готово» и «Отмене» иконки нет. Действие блокируется,
 * если у карточки есть зависимости в работе (правило проверяет board/derive.ts
 * и передаёт готовый результат). По нажатию заблокированной иконки вызываем
 * onBlocked с текстом причины — на web Alert не работает, поэтому решение
 * «где показать» принимает экран.
 *
 * Клик по названию карточки открывает форму редактирования. Кликабельность
 * включена явно (`pointer-events-auto`): карточки закрытых колонок лежат в слое
 * с `pointer-events-none`, см. комментарий у корневого `View`.
 * Признак «без проекта» — отсутствие родителя, а не отсутствие цвета:
 * у такой карточки цвет служебный (нейтральный c0).
 *
 * В нижней строке слева стоит дедлайн без времени в виде «до ДД.ММ.ГГГГ», если
 * он задан: срок виден прямо на доске, не открывая карточку; справа остаётся
 * кнопка действия.
 * Если срок прошёл, карточка получает лёгкую красную подложку, а сама дата
 * красится в цвет ошибки — просрочка видна и без чтения даты.
 *
 * Между названием и нижней строкой — хлебные крошки: путь карточки по карточкам
 * иерархии от корня к родителю. Сегменты — кодовые названия (slug) родителей, а
 * у родителя без метки — его название; сама карточка в путь не входит, её
 * название стоит строкой выше. Направление в путь не попадает, поэтому у
 * инициатив крошек нет — как и у всех карточек стратегического уровня. Путь
 * считает board/derive.ts (`cardBreadcrumbs`), компонент получает его готовым
 * списком.
 *
 * У карточки без родителя место крошек занимает другое содержимое. У «серого»
 * проекта (инициативы нет) — его собственное кодовое название, если метка
 * задана; без метки строки крошек нет вовсе. У задачи без проекта — подпись
 * «Без проекта». У инициативы крошек не бывает: её родитель направление, а оно
 * в путь не входит. Крошки обрезаются одной строкой: длинный путь в узкой
 * колонке не должен ломать высоту плитки.
 *
 * В закрытых колонках («Готово», «Отмена») ни срок, ни крошки (вместе с
 * подписью «без родителя») не выводятся и просрочка не подсвечивается: работа
 * уже завершена или отменена, дедлайн там потерял смысл (красная плитка
 * читалась бы как «просрочено» без причины), а путь по иерархии перестаёт быть
 * нужным. Признак колонки передаёт вызывающий компонент (`closedColumn`).
 */

import { Pressable, Text, View } from 'react-native';

import { CalendarIcon, CheckIcon, PlayIcon } from './BoardIcons';
import { formatDeadlineDate, isDeadlineOverdue } from '../deadline';
import { directionColorHex } from '../directionColors';
import type { CardAction, CardBreadcrumb } from '../derive';
import type { CardKind } from '../types';
import { WORK_STAGE_LABEL } from '../types';

/**
 * Разделитель сегментов крошек: «›» — компактный шеврон, привычный для пути
 * по иерархии. Отдельный элемент, а не часть подписи, чтобы при обрезке в одну
 * строку видимые сегменты оставались различимыми.
 */
const BREADCRUMB_DIVIDER = '›';

/** Иконка действия по целевой колонке: «В работе» — play, «Готово» — галочка. */
function ActionIcon({ target }: { target: CardAction['target'] }) {
  return target === 'complete' ? <CheckIcon /> : <PlayIcon />;
}

/**
 * Бейдж степени проработки: «Идея» или «На реализацию».
 *
 * Выводится только в беклоге. Идея помечена приглушённой плашкой (карточка
 * ещё не готова к работе), готовность — плашкой цвета акцента, чтобы группа
 * «на реализацию» читалась выше списка идей с первого взгляда.
 */
function StageBadge({ idea }: { idea: boolean }) {
  return (
    <View className={['rounded-full px-1.5 py-0.5', idea ? 'bg-lane' : 'bg-app/10'].join(' ')}>
      <Text className={['text-[10px] font-semibold', idea ? 'text-subtle' : 'text-app'].join(' ')}>
        {idea ? WORK_STAGE_LABEL.idea : WORK_STAGE_LABEL.ready}
      </Text>
    </View>
  );
}

/**
 * Строка крошек карточки без родителя; пустая строка — строку не рисуем.
 *
 * - проекта без инициативы (тактический уровень) — его собственное кодовое
 *   название, если оно задано; без метки строки нет;
 * - задачи без проекта — подпись «Без проекта»;
 * - инициативы — пусто: её родитель направление, а направление в крошки не
 *   попадает, поэтому у инициатив крошек не бывает вообще.
 *
 * Метка проверяется после `trim()`: пустая строка и одни пробелы — это
 * отсутствие метки, а не пустой сегмент в плитке.
 */
function standaloneCardLabel(kind: CardKind, slug: string | null): string {
  if (kind === 'project') {
    return slug?.trim() ?? '';
  }

  return kind === 'task' ? 'Без проекта' : '';
}

interface BoardCardProps {
  title: string;
  /** Цвет родителя ключом палитры; у карточки без родителя — служебный c0. */
  color: string | null;
  /**
   * Путь по иерархии от корня к родителю: сегменты строки крошек над нижней
   * строкой. Пустой массив — пути нет (карточка без родителя либо родитель не
   * загружен).
   */
  breadcrumbs: readonly CardBreadcrumb[];
  /**
   * Собственное кодовое название карточки; null — метки нет.
   *
   * Нужно «серой» карточке тактического уровня (проект без инициативы): пути по
   * иерархии у неё нет, поэтому в строке крошек показывается её метка.
   */
  slug: string | null;
  /** Есть ли у карточки родитель: если нет — подпись о недостающем родителе. */
  hasParent: boolean;
  /** Тип карточки: у проекта без родителя строка крошек особая (см. ниже). */
  kind: CardKind;
  /** Срок карточки строкой ISO-8601; null — срока нет. */
  deadline: string | null;
  /**
   * Карточка лежит в закрытой колонке («Готово», «Отмена»): срок не выводим
   * и просрочку не подсвечиваем — см. комментарий в шапке компонента.
   */
  closedColumn: boolean;
  /**
   * Степень проработки карточки: true — идея, false — готова к реализации.
   *
   * Бейдж показывается только в беклоге: степень проработки — его свойство.
   * В остальных колонках значение не выводится, хотя в данных оно сохраняется.
   */
  idea: boolean;
  /** Карточка лежит в беклоге — колонке, где выводится степень проработки. */
  backlogColumn: boolean;
  /** Действие над колонками; null — в этой колонке действий нет. */
  action: CardAction | null;
  /** Выполнить действие (перевод в следующую колонку). */
  onAction: () => void;
  /** Открыть карточку на редактирование. */
  onPress: () => void;
}

export function BoardCard({
  title,
  color,
  breadcrumbs,
  slug,
  hasParent,
  kind,
  deadline,
  closedColumn,
  idea,
  backlogColumn,
  action,
  onAction,
  onPress,
}: BoardCardProps) {
  /**
   * Строка крошек у карточки без родителя.
   *
   * У «серого» проекта (тактический уровень, инициативы нет) пути по иерархии
   * нет, поэтому в строке показывается его собственное кодовое название — и
   * только если метка задана: без метки строки нет вовсе, подписи «Без
   * инициативы» на этой карточке тоже нет.
   *
   * Задача без проекта объясняет, чего именно ей не хватает: «Без проекта».
   * У инициативы крошек не бывает в принципе: её родитель — направление, а оно
   * в путь не входит.
   */
  const withoutParentLabel = hasParent ? '' : standaloneCardLabel(kind, slug);
  // Срок рисуется без времени: для дедлайна важен сам день. В закрытых
  // колонках срок не показываем — он теряет смысл после завершения работы.
  const deadlineLabel = closedColumn ? null : formatDeadlineDate(deadline);
  // Крошки в закрытых колонках не нужны: путь по иерархии там не читают, а
  // место в плитке дороже (см. комментарий в шапке компонента). Подпись «без
  // родителя» живёт в той же строке, поэтому скрывается вместе с ней.
  const breadcrumbPath = closedColumn ? [] : breadcrumbs;
  const breadcrumbText = closedColumn ? '' : withoutParentLabel;
  // Просроченная карточка подсвечивается: срок прошёл, а работа ещё не закрыта.
  // В закрытых колонках подсветки нет — иначе завершённая задача выглядела бы
  // проблемной из-за давно прошедшего срока.
  const overdue = !closedColumn && isDeadlineOverdue(deadline);

  return (
    // `pointer-events-auto` возвращает клики самой карточке. Карточки закрытых
    // колонок («Готово», «Отмена») лежат в позиционном слое, помеченном
    // `pointer-events-none` (см. CLOSED_COLUMN_SLOT в BoardLevel.tsx), а это
    // свойство наследуемое: без явного `auto` плитка была видна, но не ловила
    // наведение и клик на web. Пустые места слота при этом остаются прозрачными
    // для кликов. На native свойство не используется — там поведение прежнее.
    <View
      className={[
        'pointer-events-auto flex-row overflow-hidden rounded border',
        overdue ? 'border-err-fg/30 bg-card-overdue' : 'border-card-line bg-card',
      ].join(' ')}
    >
      {/* Полоса цвета родителя — единственный цветной акцент карточки.
          У карточки без родителя резолвер отдаёт служебный c0. */}
      <View className="w-1 shrink-0" style={{ backgroundColor: directionColorHex(color) }} />

      {/* `min-w-0` — длинное название не расширяет карточку: у флекс-элемента
          минимальная ширина по умолчанию равна содержимому, из-за чего карточка
          в узкой колонке вылезала за её отступы. Название обрезается по
          `numberOfLines`. */}
      <View className="min-w-0 flex-1 gap-1.5 px-2.5 py-2">
        {/* Открытие карточки — отдельная область над названием: кнопка-иконка
            действия стоит рядом, а не внутри, иначе на web получится
            <button> внутри <button>. */}
        <Pressable
          accessibilityRole="button"
          accessibilityLabel={`Открыть карточку «${title}»`}
          onPress={onPress}
          className="active:opacity-70"
        >
          <Text className="text-sm font-medium leading-5 text-ink" numberOfLines={3}>
            {title}
          </Text>
        </Pressable>

        {/* Крошки: путь от корня иерархии к родителю. Стоят одной строкой и
            обрезаются, чтобы длинный путь не растягивал плитку в узкой колонке.
            У карточки без родителя вместо пути стоит либо её собственное кодовое
            название (проект без инициативы), либо подпись «Без проекта» (задача
            без проекта): это то же место плитки и тот же приглушённый стиль,
            поэтому путь и подпись не занимают две строки.
            `min-w-0` нужен по той же причине, что и блоку ниже: флекс-элемент
            по умолчанию не сжимается меньше содержимого, и путь вылез бы за
            отступы карточки вместо обрезки. */}
        {breadcrumbPath.length === 0 && breadcrumbText === '' ? null : (
          <Text className="min-w-0 text-[10px] leading-4 text-subtle" numberOfLines={1}>
            {breadcrumbPath.length === 0 ? breadcrumbText : null}

            {breadcrumbPath.map((segment, index) => (
              <Text key={`${segment.kind}-${segment.id}`}>
                {index === 0 ? null : ` ${BREADCRUMB_DIVIDER} `}
                {segment.label}
              </Text>
            ))}
          </Text>
        )}

        {/* Степень проработки видна только в беклоге: в работе и закрытых
            колонках карточка уже не «идея или нет», поэтому бейджа там нет. */}
        {backlogColumn ? <StageBadge idea={idea} /> : null}

        <View className="flex-row items-center justify-between gap-2">
          {/* Левая часть нижней строки — только срок карточки: подпись «без
              родителя» переехала в крошки, поэтому здесь ей делать нечего.
              `flex-1` держит дату у левого края, а кнопку действия — справа. */}
          <View className="min-w-0 flex-1 flex-row items-center gap-1.5">
            {deadlineLabel === null ? null : (
              /* «до» + дата: сразу понятно, что дата — это срок, а не отметка
                 создания. У просроченной карточки сама дата краснее подложки,
                 чтобы причина подсветки читалась без открытия карточки. */
              <View className="flex-row items-center gap-1">
                <CalendarIcon size={11} />

                <Text className="text-[11px] text-muted">до</Text>

                <Text
                  className={['text-[11px]', overdue ? 'font-semibold text-err-fg' : 'font-medium text-muted'].join(
                    ' ',
                  )}
                >
                  {deadlineLabel}
                </Text>
              </View>
            )}
          </View>

          {action ? (
            <Pressable
              accessibilityRole="button"
              accessibilityLabel={`${action.label}: «${title}»`}
              accessibilityState={{ disabled: action.blockReason !== null }}
              onPress={onAction}
              hitSlop={6}
              className={[
                'h-6 w-6 items-center justify-center rounded',
                action.blockReason === null ? 'bg-app active:opacity-90' : 'bg-border opacity-70',
              ].join(' ')}
            >
              <ActionIcon target={action.target} />
            </Pressable>
          ) : null}
        </View>
      </View>
    </View>
  );
}
