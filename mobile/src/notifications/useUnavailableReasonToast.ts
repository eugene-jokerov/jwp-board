/**
 * Причина недоступного действия, показываемая тостом.
 *
 * Клик по заблокированной кнопке на карточке («Взять в работу», «Завершить
 * задачу») отклоняется клиентом: запрос на сервер не уходит, причина берётся из
 * `allowed_transitions` (см. `cardAction` в `board/derive.ts`). Это не ответ
 * сервера, поэтому вид тоста — предупреждение, а не ошибка: ошибки
 * (`useFormErrorToast`, `notifyError`) остаются за 403/409 и формами.
 *
 * Почему тост, а не строка над доской: доска почти всегда прокручена, и строка
 * с причиной оказывалась за верхней границей видимой области — пользователь не
 * видел ни причины, ни самого факта отказа. Тост рисуется поверх экрана
 * (`NotificationHost`) и одинаково работает на native и на web: системный
 * `Alert` на web не показывается вовсе.
 *
 * Ключ тоста постоянный: повторный клик по заблокированной кнопке не плодит
 * копий — существующая плашка обновляется и снова получает срок жизни. Время
 * жизни — обычное для предупреждения: причина короткая и прочитанная, держать
 * её до явного закрытия незачем.
 */

import { useEffect } from 'react';

import { useNotifications } from './NotificationContext';

/**
 * Показать причину недоступного действия.
 *
 * @param reason Текст причины; `null` — показать нечего, старый тост снимается.
 * @param key Ключ тоста: повторные клики обновляют одну и ту же плашку.
 * @param title Заголовок тоста, объясняющий, что именно отклонено.
 */
export function useUnavailableReasonToast(reason: string | null, key: string, title: string): void {
  const { notifyWarning, dismissKey } = useNotifications();

  useEffect(() => {
    if (reason === null) {
      dismissKey(key);

      return;
    }

    notifyWarning(reason, { title, key });

    // Действие перестало быть заблокированным или экран ушёл — причина тоже.
    return () => {
      dismissKey(key);
    };
  }, [reason, key, title, notifyWarning, dismissKey]);
}
